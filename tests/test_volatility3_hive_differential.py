def _write_oracle_image(tmp_path, name, dat, hbins_len):
    isf_path = tmp_path / f"{name}.isf.json"
    isf_path.write_text(fake_nt_isf_json())
    img, cmhive_off = add_management(dat, hbins_len)
    img_path = tmp_path / f"{name}.img"
    img_path.write_bytes(img)
    return str(img_path), cmhive_off, str(isf_path)


