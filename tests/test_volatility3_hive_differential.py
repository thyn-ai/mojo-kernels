class TestHiveWalk:
    def test_banner(self):
        print(f"\nvol_mojo backend under test: {BACKEND}")

    def test_small_tree(self, small_tree):
        expected = oracle_walk_tuples(
            small_tree["img"], small_tree["cmhive"], small_tree["isf"]
        )
        got = vol_mojo.walk_hive(small_tree["dat"])
        assert got == expected
        assert [t[2] for t in got] == [
            "ROOT",
            "Microsoft",
            "Software",
            "Windows",
            "CurrentVersion",
        ]

    def test_ri_nested(self, ri_nested):
        expected = oracle_walk_tuples(
            ri_nested["img"], ri_nested["cmhive"], ri_nested["isf"]
        )
        got = vol_mojo.walk_hive(ri_nested["dat"])
        assert got == expected
        assert [t[2] for t in got] == [
            "ROOT",
            "ControlSet001",
            "ControlSet002",
            "Services",
            "Enum",
        ]

    def test_dirty_cells_skipped(self, dirty_cells):
        expected = oracle_walk_tuples(
            dirty_cells["img"], dirty_cells["cmhive"], dirty_cells["isf"]
        )
        got = vol_mojo.walk_hive(
            dirty_cells["dat"], storage_length=dirty_cells["storage_len"]
        )
        assert got == expected
        names = [t[2] for t in got]
        assert names[:6] == ["ROOT", "Alpha", "", "Sécurité", "ZeroList", "Beta"]
        assert names[6:] == [f"filler-{i:04d}" for i in range(300)]
        assert len(got) == 306
        # The reachable tree spans several hbins (multi-page translation).
        assert max(t[0] for t in got) > 0x4000

    def test_subtree_root_override(self, small_tree):
        """visit_nodes(visitor, node=...) from a non-root node must match."""
        full = vol_mojo.walk_hive(small_tree["dat"])
        software = next(t for t in full if t[2] == "Software")
        node_cell = software[0] - 4  # tuple offset is cell index + 4
        expected = oracle_walk_tuples(
            small_tree["img"], small_tree["cmhive"], small_tree["isf"], node_off=node_cell
        )
        got = vol_mojo.walk_hive(small_tree["dat"], root_cell_offset=node_cell)
        assert got == expected
        assert [t[2] for t in got] == ["Software", "Windows", "CurrentVersion"]

    def test_non_regf_signature_uses_0x20(self, tmp_path):
        """A non-'regf' base block makes the oracle use root cell 0x20."""
        b = HiveBuilder()
        only = b.add_cell(b.nk(b"FirstCell"))
        assert only == 0x20
        dat, hbins_len = b.build_dat(0x20)
        dat = bytearray(dat)
        dat[0:4] = b"REGF"  # wrong case: the signature check is case-sensitive
        dat = bytes(dat)
        img, cmhive, isf = _write_oracle_image(tmp_path, "nonregf", dat, hbins_len)
        expected = oracle_walk_tuples(img, cmhive, isf)
        got = vol_mojo.walk_hive(dat)
        assert got == expected == [(0x24, "_CM_KEY_NODE", "FirstCell")]

    def test_storage_bound_truncates_name_raises_both_sides(self, tmp_path, small_tree):
        """Root name beyond the storage bound: the oracle's translation
        raises; so must we (HiveError)."""
        dat = small_tree["dat"]
        root = small_tree["root"]
        # Bound the storage so the root node's name (at cell+4+0x4C) is
        # outside it, while sig/SubKeyLists/NameLength remain inside.
        storage_len = root + 4 + 0x4C - 1
        img, cmhive = add_management(dat, storage_len)
        img_path = tmp_path / "trunc.img"
        img_path.write_bytes(img)
        isf_path = tmp_path / "trunc.isf.json"
        isf_path.write_text(fake_nt_isf_json())
        with pytest.raises(Exception):
            oracle_walk_tuples(str(img_path), cmhive, str(isf_path))
        with pytest.raises(vol_mojo.HiveError):
            vol_mojo.walk_hive(dat, storage_length=storage_len)

    def test_root_not_nk_raises(self, tmp_path):
        """Root cell pointing at a non-nk cell: the oracle raises (the
        visited object has no get_subkeys); we raise HiveError."""
        b = HiveBuilder()
        root = b.add_cell(b.vk(b"NotAKey"))
        dat, hbins_len = b.build_dat(root)
        img, cmhive, isf = _write_oracle_image(tmp_path, "badroot", dat, hbins_len)
        with pytest.raises(Exception):
            oracle_walk_tuples(img, cmhive, isf)
        with pytest.raises(vol_mojo.HiveError):
            vol_mojo.walk_hive(dat)

    def test_integration_helper_matches(self, small_tree):
        got = volatility3_integration.walk_hive_tuples(small_tree["dat"])
        assert got == vol_mojo.walk_hive(small_tree["dat"])


