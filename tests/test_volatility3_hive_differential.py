"""Differential suite: vol_mojo (native + forced fallback) vs the volatility3 oracle.

The oracle is the published PyPI release volatility3==2.28.2, imported from
PYTHONPATH (``.oracle-volatility3/`` per scripts/test_all_volatility3_hive.sh).
The suite runs twice per scripts/test_all_volatility3_hive.sh: once against
the native kernel, once with VOL_MOJO_DISABLE_NATIVE=1 — both backends must
match the oracle exactly (tuple-for-tuple / hit-for-hit, order included).

Hive fixtures are small valid hives generated by
tests/test_volatility3_hive_fixtures.py — no copyrighted Windows hives are
downloaded or required.
"""

