def _builtin_buffer() -> bytes:
    """Headers exercising every builtin tag with accept/reject variety."""
    buf = bytearray(b"\x00" * 0x800)
    # Proc: pass (nonpaged, big), reject (small), pass (free).
    put_header_x64(buf, 0x040, 0, 0x41, 2, b"Proc")
    put_header_x64(buf, 0x0C0, 0, 0x10, 2, b"Proc")
    put_header_x64(buf, 0x140, 0, 0x41, 0, b"Proc")
    # Pro\xe3 (pre-win8 process): pass nonpaged; reject paged.
    put_header_x64(buf, 0x1A0, 0, 0x41, 2, b"Pro\xe3")
    put_header_x64(buf, 0x200, 0, 0x41, 1, b"Pro\xe3")
    # Thre/Thr\xe5: pass + small reject.
    put_header_x64(buf, 0x260, 0, 0x40, 2, b"Thre")
    put_header_x64(buf, 0x2C0, 0, 0x05, 2, b"Thre")
    put_header_x64(buf, 0x320, 0, 0x40, 2, b"Thr\xe5")
    # File/Fil\xe5: pass; paged reject.
    put_header_x64(buf, 0x380, 0, 0x10, 2, b"File")
    put_header_x64(buf, 0x3E0, 0, 0x10, 1, b"File")
    put_header_x64(buf, 0x440, 0, 0x10, 2, b"Fil\xe5")
    # Muta/Mut\xe1: pass at exactly 64; reject below.
    put_header_x64(buf, 0x4A0, 0, 0x04, 2, b"Muta")
    put_header_x64(buf, 0x500, 0, 0x03, 2, b"Mut\xe1")
    # Driv/Dri\xf6: pass (0x10*0x10=256 >= 248), free pass.
    put_header_x64(buf, 0x560, 0, 0x10, 2, b"Driv")
    put_header_x64(buf, 0x5C0, 0, 0x10, 0, b"Dri\xf6")
    # MmLd: pass (0x05*0x10=80 >= 76).
    put_header_x64(buf, 0x620, 0, 0x05, 2, b"MmLd")
    # Symb/Sym\xe2: PAGED|FREE: pass paged; reject nonpaged.
    put_header_x64(buf, 0x680, 0, 0x05, 1, b"Symb")
    put_header_x64(buf, 0x6E0, 0, 0x05, 2, b"Symb")
    put_header_x64(buf, 0x740, 0, 0x05, 1, b"Sym\xe2")
    # CM10: PAGED|FREE, >= 800 (0x32*0x10=800): pass with odd PoolType 3.
    put_header_x64(buf, 0x7A0, 0, 0x32, 3, b"CM10")
    # Stray tag at offset 0: raw header offset -4 wraps to 0x7FC through the
    # layer address mask (0x7FF for a 0x800-byte buffer) and reads zeros, so
    # it fails the size check on both sides.
    buf[0x000:0x004] = b"Proc"
    return bytes(buf)


